export function getLocale() {
  let lang = "en";
  try {
    lang = app.ui?.settings?.getSettingValue?.("Comfy.Locale") ||
      navigator.language || "en";
  } catch {
    lang = "en";
  }
  if (STRINGS[lang]) return lang;
  const base = String(lang).split("-")[0];
  return STRINGS[base] ? base : "en";
}

export function t(key, vars) {
  let s = STRINGS[getLocale()]?.[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

// 서버가 코드와 함께 반환한 에러를 로케일 문자열로, 미지원 코드는 원문 그대로.
export function serverError(data, status) {
  const code = data?.code;
  const map = {
    session_missing_reload: "err.session_missing_reload",
    session_missing_run: "err.session_missing_run",
    file_not_found: "err.file_not_found",
    not_psd: "err.not_psd",
    bad_type: "err.bad_type",
  };
  if (code === "session_missing") return null; // 호출측이 문맥(reload/run)에 맞게 처리
  if (code && map[code]) return t(map[code], { detail: data.detail ?? "" });
  return data?.error || String(status);
}

// 경고 목록({code,name,detail?}[]) → 로케일 문자열 배열
export function formatWarnings(warnings) {
  return (warnings || []).map((w) =>
    typeof w === "string" ? w : t(`warn.${w.code}`, { name: w.name ?? "", detail: w.detail ?? "" })
  );
}
